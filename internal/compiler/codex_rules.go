package compiler

import (
	"fmt"
	"slices"
	"strconv"
	"strings"

	"github.com/withnic/reifu/internal/model"
)

// CompileCodexRules compiles .reifu.jsonc permissions.deny_commands into a
// Codex CLI execpolicy Starlark rules file (.codex/rules/reifu.rules) using
// prefix_rule(..., decision = "forbidden"). It returns (nil, false, nil) when
// no deny rules apply.
func CompileCodexRules(cfg model.ReifuConfig) ([]byte, bool, error) {
	if err := validateDenyCommands(cfg.Permissions.DenyCommands); err != nil {
		return nil, false, err
	}
	var rules []string
	seen := make(map[string]bool)
	for _, raw := range cfg.Permissions.DenyCommands {
		tokens := parseCodexDenyTokens(raw)
		if len(tokens) == 0 {
			continue
		}
		expr := formatCodexPattern(tokens)
		if seen[expr] {
			continue
		}
		seen[expr] = true
		rules = append(rules, fmt.Sprintf(
			"prefix_rule(\n    pattern = %s,\n    decision = \"forbidden\",\n    justification = \"Blocked by reifu deny_commands\",\n)\n",
			expr,
		))
	}
	if len(rules) == 0 {
		return nil, false, nil
	}
	var out strings.Builder
	out.WriteString("# Generated by reifu from .reifu.jsonc permissions.deny_commands.\n")
	out.WriteString("# Add custom rules in a separate .codex/rules/*.rules file.\n\n")
	out.WriteString(strings.Join(rules, "\n"))
	return []byte(out.String()), true, nil
}

func validateDenyCommands(commands []string) error {
	for i, cmd := range commands {
		if strings.ContainsAny(cmd, "\r\n\x00") {
			return fmt.Errorf("permissions.deny_commands[%d]: contains a control character", i)
		}
	}
	return nil
}

// parseCodexDenyTokens splits a reifu glob command pattern into prefix tokens
// suitable for Codex prefix_rule patterns. Internal wildcards such as
// "Remove-Item*-Recurse*" are split into separate literal prefix tokens.
func parseCodexDenyTokens(raw string) []string {
	var tokens []string
	for _, field := range strings.Fields(raw) {
		for _, part := range strings.Split(field, "*") {
			part = strings.Trim(part, "?")
			if part != "" {
				tokens = append(tokens, part)
			}
		}
	}
	return tokens
}

func formatCodexPattern(tokens []string) string {
	ci := len(tokens) > 0 && isCaseInsensitiveWindowsCommand(tokens[0])
	parts := make([]string, 0, len(tokens))
	for i, tok := range tokens {
		if !ci {
			parts = append(parts, strconv.Quote(tok))
			continue
		}
		choices := codexCaseChoices(tok, i == 0)
		if len(choices) == 1 {
			parts = append(parts, strconv.Quote(choices[0]))
			continue
		}
		quoted := make([]string, len(choices))
		for j, c := range choices {
			quoted[j] = strconv.Quote(c)
		}
		parts = append(parts, "["+strings.Join(quoted, ", ")+"]")
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

func codexCaseChoices(token string, isCommand bool) []string {
	var choices []string
	add := func(s string) {
		if s != "" && !slices.Contains(choices, s) {
			choices = append(choices, s)
		}
	}
	add(token)
	lower := strings.ToLower(token)
	upper := strings.ToUpper(token)
	if isCommand {
		add(lower)
		add(upper)
		return choices
	}
	if lower == "-recurse" {
		add("-recurse")
		add("-r")
		return choices
	}
	if strings.HasPrefix(token, "/") || strings.HasPrefix(token, "-") {
		add(lower)
		add(upper)
	}
	return choices
}
